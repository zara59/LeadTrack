/**
 * Parameterized PostgreSQL queries for leads and dashboard statistics.
 *
 * Ownership: the userId passed into every function comes from the verified JWT
 * (req.user.id), never from the request body. All queries are scoped by it, so
 * one user can never read or mutate another user's leads — enforced by the
 * backend and by the database.
 */
import { pool } from './pool.js';

/** pg timestamptz rows arrive as Date objects -> API ISO strings. */
export function rowToLead(row) {
  return {
    id: row.id,
    name: row.name,
    company: row.company,
    email: row.email,
    phone: row.phone,
    source: row.source,
    status: row.status,
    notes: row.notes,
    createdAt:
      row.created_at instanceof Date ? row.created_at.toISOString() : row.created_at,
    updatedAt:
      row.updated_at instanceof Date ? row.updated_at.toISOString() : row.updated_at,
  };
}

/** Escape LIKE/ILIKE wildcards so a user's `%`/`_` is matched literally. */
function escapeLike(term) {
  return term.replace(/[\\%_]/g, '\\$&');
}

/**
 * GET /api/leads — only the authenticated user's leads, with optional
 * status/source/search filters applied inside that ownership scope.
 */
export async function listLeads({ userId, status, source, search } = {}) {
  const where = [`user_id = $1`];
  const params = [userId];

  if (status) {
    params.push(status);
    where.push(`status = $${params.length}`);
  }
  if (source) {
    params.push(source);
    where.push(`source = $${params.length}`);
  }
  if (search) {
    params.push(`%${escapeLike(search)}%`);
    where.push(`(name ILIKE $${params.length} ESCAPE '\\'
                OR company ILIKE $${params.length} ESCAPE '\\'
                OR email ILIKE $${params.length} ESCAPE '\\')`);
  }

  const sql = `
    SELECT *
    FROM leads
    WHERE ${where.join(' AND ')}
    ORDER BY created_at DESC, id DESC`;

  const { rows } = await pool.query(sql, params);
  return rows.map(rowToLead);
}

/**
 * GET /api/leads/:id — returns null when the id does not exist OR belongs to
 * another user (callers surface that as a 404 so existence is not revealed).
 */
export async function findLead(id, userId) {
  const { rows } = await pool.query(
    'SELECT * FROM leads WHERE id = $1 AND user_id = $2',
    [id, userId],
  );
  return rows.length ? rowToLead(rows[0]) : null;
}

/**
 * POST /api/leads — id + timestamps are generated by the database; ownership
 * (user_id) is supplied by the backend from the authenticated request.
 */
export async function insertLead(fields, userId) {
  const { rows } = await pool.query(
    `WITH seq AS (SELECT nextval('leads_id_seq') AS n)
     INSERT INTO leads (id, user_id, name, company, email, phone, source, status, notes)
     SELECT 'LT-' || seq.n, $1, $2, $3, $4, $5, $6, $7, $8
     FROM seq
     RETURNING *`,
    [userId, fields.name, fields.company, fields.email, fields.phone, fields.source, fields.status, fields.notes],
  );
  return rows.length ? rowToLead(rows[0]) : null;
}

/**
 * PATCH /api/leads/:id — updates only the supplied fields, and only when the
 * lead belongs to the authenticated user.
 */
export async function updateLead(id, patch, userId) {
  const columns = Object.keys(patch);
  if (columns.length === 0) return null;

  const assignments = columns.map((column, index) => `${column} = $${index + 1}`);
  const values = columns.map((column) => patch[column]);
  values.push(id, userId);

  const { rows } = await pool.query(
    `UPDATE leads
     SET ${assignments.join(', ')}, updated_at = now()
     WHERE id = $${values.length - 1} AND user_id = $${values.length}
     RETURNING *`,
    values,
  );
  return rows.length ? rowToLead(rows[0]) : null;
}

/** DELETE /api/leads/:id — only when the lead belongs to the authenticated user. */
export async function removeLead(id, userId) {
  const { rowCount } = await pool.query(
    'DELETE FROM leads WHERE id = $1 AND user_id = $2',
    [id, userId],
  );
  return rowCount > 0;
}

/**
 * GET /api/dashboard/stats — aggregated in PostgreSQL, scoped to the
 * authenticated user's leads only. Nothing is hardcoded.
 */
export async function dashboardStats(userId) {
  const { rows } = await pool.query(
    `SELECT
       count(*)::int                                 AS total_leads,
       count(*) FILTER (WHERE status = 'new')::int       AS new_leads,
       count(*) FILTER (WHERE status = 'contacted')::int AS contacted_leads,
       count(*) FILTER (WHERE status = 'qualified')::int AS qualified_leads,
       count(*) FILTER (WHERE status = 'won')::int       AS won_leads,
       count(*) FILTER (WHERE status = 'lost')::int      AS lost_leads,
       CASE
         WHEN count(*) = 0 THEN 0
         ELSE round(100.0 * count(*) FILTER (WHERE status = 'won') / count(*))::int
       END                                          AS conversion_rate
     FROM leads
     WHERE user_id = $1`,
    [userId],
  );

  const s = rows[0];
  return {
    totalLeads: s.total_leads,
    newLeads: s.new_leads,
    contactedLeads: s.contacted_leads,
    qualifiedLeads: s.qualified_leads,
    wonLeads: s.won_leads,
    lostLeads: s.lost_leads,
    conversionRate: s.conversion_rate,
  };
}